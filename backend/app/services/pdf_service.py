from typing import List, Optional
from fpdf import FPDF
from app.models.entities import (
    ClinicalEncounter,
    ClinicSetting,
    Invoice,
    PatientProfile,
    Payment,
    Prescription,
    Receipt,
    TreatmentPlan,
    TreatmentRecord,
)


def _safe_ascii(text: Optional[str]) -> str:
    if not text:
        return ""
    return (
        str(text)
        .replace("–", "-")
        .replace("—", "-")
        .replace("’", "'")
        .replace("“", '"')
        .replace("”", '"')
        .encode("latin-1", errors="replace")
        .decode("latin-1")
    )


class RumiBrandedPDF(FPDF):
    def __init__(self, clinic_name: str, address: str, phone: str, doc_title: str):
        super().__init__()
        self.clinic_name = _safe_ascii(clinic_name)
        self.address = _safe_ascii(address)
        self.phone = _safe_ascii(phone)
        self.doc_title = _safe_ascii(doc_title)
        self.set_auto_page_break(auto=True, margin=18)

    def header(self):
        # Brand header bar (#01578c deep dental blue)
        self.set_fill_color(1, 87, 140)
        self.rect(0, 0, 210, 28, style="F")
        self.set_xy(12, 7)
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 16)
        self.cell(120, 7, self.clinic_name, ln=0)
        self.set_font("Helvetica", "B", 12)
        self.cell(66, 7, self.doc_title, ln=1, align="R")

        self.set_x(12)
        self.set_font("Helvetica", "", 8.5)
        self.cell(186, 5, f"{self.address}  |  Tel: {self.phone}  |  https://rumidentalcare.com", ln=1)
        self.ln(8)
        self.set_text_color(35, 35, 35)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(110, 110, 110)
        self.cell(
            0,
            6,
            f"Generated by {self.clinic_name} Official Clinical & Billing System  |  Page {self.page_no()}",
            align="C",
        )


def generate_invoice_pdf(invoice: Invoice, clinic: ClinicSetting) -> bytes:
    title = "COST ESTIMATE" if invoice.document_kind == "Estimate" else "OFFICIAL INVOICE"
    pdf = RumiBrandedPDF(clinic.clinic_name, clinic.address_line, clinic.phone_primary, title)
    pdf.add_page()

    patient = invoice.patient
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(95, 6, f"Document #: {_safe_ascii(invoice.invoice_number)}", ln=0)
    pdf.cell(95, 6, f"Issue Date: {invoice.issue_date.isoformat()}", ln=1, align="R")

    pdf.set_font("Helvetica", "", 10)
    pdf.cell(95, 6, f"Patient Name: {_safe_ascii(patient.full_name if patient else '')}", ln=0)
    pdf.cell(95, 6, f"Status: {_safe_ascii(invoice.status)}", ln=1, align="R")

    pdf.cell(95, 6, f"Patient Number: {_safe_ascii(patient.patient_number if patient else '')}", ln=0)
    pdf.cell(95, 6, f"Currency: {_safe_ascii(invoice.currency)}", ln=1, align="R")
    pdf.ln(5)

    # Table Header
    pdf.set_fill_color(240, 247, 250)
    pdf.set_font("Helvetica", "B", 9.5)
    pdf.cell(90, 8, "Service / Procedure Description", border=1, fill=True)
    pdf.cell(20, 8, "Tooth", border=1, align="C", fill=True)
    pdf.cell(20, 8, "Qty", border=1, align="C", fill=True)
    pdf.cell(28, 8, "Unit (PKR)", border=1, align="R", fill=True)
    pdf.cell(32, 8, "Total (PKR)", border=1, align="R", fill=True, ln=1)

    pdf.set_font("Helvetica", "", 9.5)
    for item in invoice.line_items:
        pdf.cell(90, 7, _safe_ascii(item.description)[:48], border=1)
        pdf.cell(20, 7, _safe_ascii(item.tooth_fdi or "-"), border=1, align="C")
        pdf.cell(20, 7, str(item.quantity), border=1, align="C")
        pdf.cell(28, 7, f"{item.unit_price:,.2f}", border=1, align="R")
        pdf.cell(32, 7, f"{item.line_total:,.2f}", border=1, align="R", ln=1)

    pdf.ln(4)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(140, 6, "Subtotal:", align="R")
    pdf.cell(50, 6, f"PKR {invoice.subtotal:,.2f}", align="R", ln=1)

    if invoice.discount_amount and invoice.discount_amount > 0:
        pdf.cell(140, 6, f"Discount ({_safe_ascii(invoice.discount_reason or 'Approved')}):", align="R")
        pdf.cell(50, 6, f"- PKR {invoice.discount_amount:,.2f}", align="R", ln=1)

    if invoice.tax_amount and invoice.tax_amount > 0:
        pdf.cell(140, 6, "Tax:", align="R")
        pdf.cell(50, 6, f"PKR {invoice.tax_amount:,.2f}", align="R", ln=1)

    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(140, 7, "Total Amount:", align="R")
    pdf.cell(50, 7, f"PKR {invoice.total_amount:,.2f}", align="R", ln=1)

    pdf.set_font("Helvetica", "", 10)
    pdf.cell(140, 6, "Recorded Payments Received:", align="R")
    pdf.cell(50, 6, f"PKR {invoice.amount_paid:,.2f}", align="R", ln=1)

    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(140, 7, "Remaining Balance Due:", align="R")
    pdf.cell(50, 7, f"PKR {invoice.balance_due:,.2f}", align="R", ln=1)

    if invoice.notes:
        pdf.ln(6)
        pdf.set_font("Helvetica", "I", 9)
        pdf.multi_cell(0, 5, f"Notes: {_safe_ascii(invoice.notes)}")

    pdf.ln(6)
    pdf.set_font("Helvetica", "I", 8.5)
    pdf.multi_cell(
        0,
        5,
        "Note: An invoice or estimate is a billing statement. Official payment receipts are issued strictly "
        "against verified payments recorded in the clinic ledger.",
    )
    return bytes(pdf.output())


