def generate_prescription_pdf(prescription: Prescription, clinic: ClinicSetting) -> bytes:
    pdf = RumiBrandedPDF(clinic.clinic_name, clinic.address_line, clinic.phone_primary, "CLINICAL PRESCRIPTION (Rx)")
    pdf.add_page()

    patient = prescription.patient
    doctor = prescription.doctor
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(95, 6, f"Rx Number: {_safe_ascii(prescription.prescription_number)}", ln=0)
    pdf.cell(95, 6, f"Issue Date: {prescription.issue_date.isoformat()}", ln=1, align="R")

    pdf.set_font("Helvetica", "", 10)
    pdf.cell(95, 6, f"Patient: {_safe_ascii(patient.full_name if patient else '')} ({_safe_ascii(patient.patient_number if patient else '')})", ln=0)
    pdf.cell(95, 6, f"Prescribing Doctor: {_safe_ascii(doctor.full_name if doctor else '')}", ln=1, align="R")
    pdf.ln(5)

    if prescription.diagnosis_notes:
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(0, 6, "Clinical Diagnosis / Indication:", ln=1)
        pdf.set_font("Helvetica", "", 9.5)
        pdf.multi_cell(0, 5, _safe_ascii(prescription.diagnosis_notes))
        pdf.ln(3)

    pdf.set_fill_color(240, 247, 250)
    pdf.set_font("Helvetica", "B", 9.5)
    pdf.cell(65, 8, "Medication & Strength", border=1, fill=True)
    pdf.cell(35, 8, "Dosage & Route", border=1, fill=True)
    pdf.cell(45, 8, "Frequency", border=1, fill=True)
    pdf.cell(45, 8, "Duration", border=1, fill=True, ln=1)

    pdf.set_font("Helvetica", "", 9.5)
    for item in prescription.items:
        med_label = f"{item.medication_name} {item.strength or ''}".strip()
        pdf.cell(65, 7, _safe_ascii(med_label)[:34], border=1)
        pdf.cell(35, 7, _safe_ascii(f"{item.dosage} ({item.route})")[:20], border=1)
        pdf.cell(45, 7, _safe_ascii(item.frequency)[:24], border=1)
        pdf.cell(45, 7, _safe_ascii(item.duration)[:24], border=1, ln=1)
        if item.instructions:
            pdf.set_font("Helvetica", "I", 8.5)
            pdf.cell(190, 6, f"   Directions: {_safe_ascii(item.instructions)[:95]}", border="LRB", ln=1)
            pdf.set_font("Helvetica", "", 9.5)

    if prescription.general_instructions:
        pdf.ln(5)
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(0, 6, "General Instructions:", ln=1)
        pdf.set_font("Helvetica", "", 9.5)
        pdf.multi_cell(0, 5, _safe_ascii(prescription.general_instructions))

    pdf.ln(12)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 6, f"Signed: {_safe_ascii(doctor.full_name if doctor else clinic.lead_dentist_name)}", ln=1, align="R")
    return bytes(pdf.output())


def generate_treatment_summary_pdf(
    patient: PatientProfile,
    encounters: List[ClinicalEncounter],
    treatments: List[TreatmentRecord],
    plans: List[TreatmentPlan],
    clinic: ClinicSetting,
) -> bytes:
    pdf = RumiBrandedPDF(
        clinic.clinic_name, clinic.address_line, clinic.phone_primary, "AUTHORIZED DENTAL SUMMARY"
    )
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(95, 6, f"Patient Name: {_safe_ascii(patient.full_name)}", ln=0)
    pdf.cell(95, 6, f"Patient ID: {_safe_ascii(patient.patient_number)}", ln=1, align="R")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(95, 6, f"Phone: {_safe_ascii(patient.phone)}", ln=0)
    pdf.cell(95, 6, f"City: {_safe_ascii(patient.city)}", ln=1, align="R")
    pdf.ln(4)

    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 7, "1. Recorded Dental Treatments", ln=1)
    pdf.set_font("Helvetica", "", 9.5)
    if not treatments:
        pdf.cell(0, 6, "No completed dental treatments recorded yet.", ln=1)
    else:
        for t in treatments:
            pdf.multi_cell(
                0,
                5.5,
                _safe_ascii(
                    f"- [{t.performed_date.isoformat()}] {t.procedure_name} "
                    f"(Tooth FDI: {t.tooth_fdi or 'General'}): {t.clinical_description}"
                ),
            )
    pdf.ln(3)

    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 7, "2. Active & Historical Treatment Plans", ln=1)
    pdf.set_font("Helvetica", "", 9.5)
    if not plans:
        pdf.cell(0, 6, "No treatment plans recorded.", ln=1)
    else:
        for p in plans:
            pdf.multi_cell(
                0,
                5.5,
                _safe_ascii(
                    f"- {p.plan_number}: {p.title} | Status: {p.status} | Est. PKR {p.total_estimated_cost:,.2f}"
                ),
            )
    pdf.ln(3)

    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 7, "3. Clinical Consultations & Examinations", ln=1)
    pdf.set_font("Helvetica", "", 9.5)
    if not encounters:
        pdf.cell(0, 6, "No clinical encounters recorded.", ln=1)
    else:
        for e in encounters:
            pdf.multi_cell(
                0,
                5.5,
                _safe_ascii(
                    f"- [{e.visit_date.isoformat()}] {e.encounter_number} ({e.status}): "
                    f"Complaint: {e.presenting_complaint} | Diagnosis: {e.diagnosis_summary or 'N/A'}"
                ),
            )
    return bytes(pdf.output())
